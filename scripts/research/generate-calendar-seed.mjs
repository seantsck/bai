// Generates database/migrations/015_reference_calendars.sql from research/calendars/*.json (sourced 2026-10-19).
// Run once to create the migration; applied migrations are frozen, so later calendar corrections go through a new
// migration or an ingestion batch, never by regenerating 015.
//   node scripts/research/generate-calendar-seed.mjs [--force]
import fs from 'node:fs'
import path from 'node:path'
import { repoRoot } from '../db/lib/migrations.mjs'

const out = path.join(repoRoot, 'database/migrations/015_reference_calendars.sql')
if (fs.existsSync(out) && !process.argv.includes('--force')) {
  console.error('015_reference_calendars.sql exists (migrations are frozen once applied); pass --force only before it is applied anywhere')
  process.exit(1)
}

const read = (f) => JSON.parse(fs.readFileSync(path.join(repoRoot, 'research/calendars', f), 'utf8'))
const draft = read('draft_calendars.json')
const intl = read('international_periods.json')
const q = (v) => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`
const d = (v) => v ? `date ${q(v)}` : 'null'
const SOURCE_TYPE = { OFFICIAL: 'OFFICIAL_LEAGUE', PRIMARY_PUBLIC: 'PUBLIC_RECORD', AGGREGATOR: 'REFERENCE_DATABASE' }

// Rules eras, summarized in BAI's own words from the cited sources. Draft and international eras differ in timing.
const ERAS = [
  ['DRAFT_CBA_2012_2016', 'Draft: 2012-2016 Basic Agreement', null, '2016-12-01',
    'Signing-bonus pools for the first 10 rounds with tax / pick-forfeiture penalties, Competitive Balance rounds, 40 rounds. Governed the 2015 and 2016 drafts. Effective start not established from an acceptable source.',
    'sbd-2011-cba'],
  ['DRAFT_CBA_2017_2021', 'Draft: 2017-2021 Basic Agreement', '2016-12-01', '2021-12-01',
    '40-round draft 2017-2019. The March 26, 2020 pandemic agreement let MLB hold a 5-round 2020 draft (remote, $20,000 cap on undrafted signings) and a 20-round 2021 draft moved to July / All-Star week.',
    'mlb-2016-tentative-cba'],
  ['DRAFT_CBA_2022_2026', 'Draft: 2022-2026 Basic Agreement', '2022-03-10', '2026-12-01',
    '20 rounds made permanent; draft combine; draft lottery for the top six picks from 2023; Prospect Promotion Incentive picks. Governed the 2022-2026 drafts.',
    'mlb-cba-draft-changes-2022'],
  ['INTL_CBA_2012_2016', 'International: 2012-2016 Basic Agreement', '2012-07-02', '2017-06-15',
    'Soft-capped bonus pools with tiered overage tax and later per-player bonus limits. Tier details changed during the agreement and sources disagree on them; confirm against the CBA text before relying on tiers. Covers the 2012-13 through 2016-17 periods.',
    'mlb-teams-dictate-market-2015'],
  ['INTL_CBA_2017_2021', 'International: 2017-2021 Basic Agreement', '2017-07-02', '2021-12-01',
    'Hard-capped bonus pools from 2017-18; exemption raised to age 25 with 6 foreign professional seasons. Pandemic changes: 2019-20 extended to Oct 15, 2020; 2020-21 moved to Jan 15 - Dec 15, 2021.',
    'fangraphs-j2-primer-2017'],
  ['INTL_CBA_2022_2026', 'International: 2022-2026 Basic Agreement', '2022-03-10', '2026-12-01',
    "Hard-capped pools continue with Jan 15 - Dec 15 periods. An international draft was proposed but the union rejected MLB's final offer on July 25, 2022. The agreement expires Dec 1, 2026, before the 2026 period's scheduled close.",
    'ap-intl-draft-rejected-2022']
]
const DRAFT_ERA = { CBA_2012_2016: 'DRAFT_CBA_2012_2016', CBA_2017_2021: 'DRAFT_CBA_2017_2021', CBA_2022_2026: 'DRAFT_CBA_2022_2026' }
const INTL_ERA = { CBA_2012_2016: 'INTL_CBA_2012_2016', CBA_2017_2021: 'INTL_CBA_2017_2021', CBA_2022_2026: 'INTL_CBA_2022_2026' }

// Primary citation: the strongest source with evidence for the row (official first, then the most-cited).
const RANK = { OFFICIAL: 1, PRIMARY_PUBLIC: 2, REPUTABLE_SECONDARY: 3, AGGREGATOR: 4, ARCHIVE: 5, OTHER: 6 }
function primarySource (row, sources) {
  const byKey = new Map(sources.map((s) => [s.key, s]))
  const keys = [...new Set(row.evidence.filter((e) => e.field === 'start_date' || e.field === 'end_date').map((e) => e.source_key))]
  return keys.sort((a, b) => RANK[byKey.get(a).authority] - RANK[byKey.get(b).authority] || a.localeCompare(b))[0]
}

const lines = []
const L = (s) => lines.push(s)
L(`-- 015_reference_calendars
-- Sourced MLB calendars for 2015-2026: Rule 4 drafts and international signing periods, with rules eras.
-- GENERATED by scripts/research/generate-calendar-seed.mjs from research/calendars/*.json (research date ${draft.retrieved_date}).
--
-- Rules encoded here:
--   * Every calendar row cites a primary source; every supporting claim is a source_observation, so the evidence for each
--     date and round count stays queryable.
--   * Where a source disagreed, its value is kept as an observation and the choice is recorded in fact_resolutions with a
--     rationale. Nothing is chosen silently.
--   * The 2026 international period's end date is the scheduled close (not yet reached on the research date).
--   * Many official MLB.com pages refused automated fetches; those sources say so in their notes (seen via search excerpts).
--   * Convergent: re-running inserts nothing new (on conflict do nothing).
`)

const allSources = [...draft.sources, ...intl.sources]
L('insert into public.sources (source_key, source_type, title, publisher, url, published_date, retrieved_date, authority_level, notes) values')
L(allSources.map((s) => `  (${q('cal:' + s.key)}, ${q(SOURCE_TYPE[s.authority] ?? 'NEWS_REPORT')}, ${q(s.title)}, ${q(s.publisher)}, ${q(s.url)}, ${d(s.published_date)}, ${d(draft.retrieved_date)}, ${q(s.authority)}, ${q(s.notes)})`).join(',\n'))
L('on conflict (source_key) do nothing;\n')

L('insert into public.rules_eras (rules_era_key, label, effective_from, effective_to, summary, source_id) values')
L(ERAS.map(([k, l, f, t, s, src]) => `  (${q(k)}, ${q(l)}, ${d(f)}, ${d(t)}, ${q(s)}, (select id from public.sources where source_key = ${q('cal:' + src)}))`).join(',\n'))
L('on conflict (rules_era_key) do nothing;\n')

L('-- Drafts (Rule 4 first-year player draft; draft_kind JUNE_AMATEUR covers it whether held in June or July)')
L('insert into public.drafts (draft_key, draft_year, draft_kind, start_date, end_date, total_rounds, structure_note, source_id, rules_era_id) values')
L(draft.drafts.map((r) => `  (${q(r.year + '-JUNE_AMATEUR')}, ${r.year}, 'JUNE_AMATEUR', ${d(r.start_date)}, ${d(r.end_date)}, ${r.total_rounds ?? 'null'}, ${q(r.notes)},
   (select id from public.sources where source_key = ${q('cal:' + primarySource(r, draft.sources))}), (select id from public.rules_eras where rules_era_key = ${q(DRAFT_ERA[r.rules_era])}))`).join(',\n'))
L('on conflict (draft_key) do nothing;\n')

L('-- International signing periods (date ranges; never calendar years)')
L('insert into public.international_signing_periods (period_key, label, start_date, end_date, rules_note, timing_note, source_id, rules_era_id) values')
L(intl.periods.map((r) => `  (${q(r.period_key)}, ${q(r.label)}, ${d(r.start_date)}, ${d(r.end_date)}, ${q(r.rules_era)}, ${q(r.notes)},
   (select id from public.sources where source_key = ${q('cal:' + primarySource(r, intl.sources))}), (select id from public.rules_eras where rules_era_key = ${q(INTL_ERA[r.rules_era])}))`).join(',\n'))
L('on conflict (period_key) do nothing;\n')

// Observations: one per (source, row, field) supporting claim.
const obs = []
// Date claims are stored as ISO dates when the evidence states one (a trailing time or '(scheduled)' qualifier stays in the
// locator); free-text claims that state no date are kept under <field>_claim so the evidence is not lost.
const ISO = /^(\d{4}-\d{2}-\d{2})\b/
function claim (field, v) {
  if (field === 'total_rounds') return /^\d+$/.test(String(v)) ? [field, String(Number(v))] : ['total_rounds_claim', JSON.stringify(String(v))]
  const m = ISO.exec(String(v))
  return m ? [field, JSON.stringify(m[1])] : [`${field}_claim`, JSON.stringify(String(v))]
}
for (const r of draft.drafts) {
  for (const e of r.evidence) {
    const [field, value] = e.field === 'rules_era' ? ['rules_era_key', JSON.stringify(DRAFT_ERA[e.value] ?? e.value)] : claim(e.field, e.value)
    obs.push(['drafts', `(select id from public.drafts where draft_key = ${q(r.year + '-JUNE_AMATEUR')})`, field, value, e.source_key, [e.locator, e.value !== undefined && !ISO.test(String(e.value)) ? null : (String(e.value).length > 10 ? `stated as: ${e.value}` : null)].filter(Boolean).join('; ')])
  }
}
for (const r of intl.periods) {
  for (const e of r.evidence) {
    const [field, value] = e.field === 'rules_era' ? ['rules_era_key', JSON.stringify(INTL_ERA[e.value] ?? e.value)] : claim(e.field, e.value)
    obs.push(['international_signing_periods', `(select id from public.international_signing_periods where period_key = ${q(r.period_key)})`, field, value, e.source_key, [e.locator, e.value !== undefined && !ISO.test(String(e.value)) ? null : (String(e.value).length > 10 ? `stated as: ${e.value}` : null)].filter(Boolean).join('; ')])
  }
}
// Disagreeing claims kept as observations (each then resolved below with a rationale).
obs.push(['drafts', "(select id from public.drafts where draft_key = '2019-JUNE_AMATEUR')", 'end_date', '"2019-06-06"', 'mlb-2019-completes', 'search excerpt phrasing'])
obs.push(['international_signing_periods', "(select id from public.international_signing_periods where period_key = '2018-19')", 'end_date', '"2019-06-25"', 'cbs-ifa-history-claim', 'retrospective explainer: "July 2 to June 25"'])

// One active observation per (source, subject, field): keep the first claim per key.
const seen = new Set()
const uniq = obs.filter(([t, s, f, , src]) => { const k = [t, s, f, src].join('|'); if (seen.has(k)) return false; seen.add(k); return true })
L('insert into public.source_observations (source_id, subject_table, subject_id, field_name, observed_value, locator, observed_on)')
L('select s.id, v.subject_table, v.subject_id, v.field_name, v.observed_value::jsonb, v.locator, ' + d(draft.retrieved_date) + ' from (values')
L(uniq.map(([t, s, f, v, src, loc]) => `  (${q(t)}, ${s}, ${q(f)}, ${q(v)}, ${q('cal:' + src)}, ${q(loc)})`).join(',\n'))
L(`) v (subject_table, subject_id, field_name, observed_value, source_key, locator)
join public.sources s on s.source_key = v.source_key
where not exists (select 1 from public.source_observations o where o.source_id = s.id and o.subject_table = v.subject_table
                  and o.subject_id = v.subject_id and o.field_name = v.field_name and o.status = 'ACTIVE');
`)

const resolution = (table, subject, value, rationale) => `insert into public.fact_resolutions (subject_table, subject_id, field_name, chosen_observation_id, considered_observation_ids, rule, decided_by, rationale)
select ${q(table)}, x.subject_id, 'end_date',
       (select min(o.id) from public.source_observations o where o.subject_table = ${q(table)} and o.subject_id = x.subject_id and o.field_name = 'end_date' and o.status = 'ACTIVE' and o.observed_value = '${value}'::jsonb),
       (select array_agg(o.id order by o.id) from public.source_observations o where o.subject_table = ${q(table)} and o.subject_id = x.subject_id and o.field_name = 'end_date' and o.status = 'ACTIVE'),
       'REQUIRE_OPERATOR', 'bai-research calendar review ${draft.retrieved_date}', ${q(rationale)}
from (select ${subject} as subject_id) x
on conflict do nothing;
`
L('-- Recorded decisions for the disagreements above (operator review; rationale kept with the evidence).')
L(resolution('drafts', "(select id from public.drafts where draft_key = '2019-JUNE_AMATEUR')", '"2019-06-05"',
  'The official schedule and the full-text aggregator put rounds 11-40 on Wed June 5; the June 6 phrasing matches the completion press release date, not a draft day.'))
L(resolution('international_signing_periods', "(select id from public.international_signing_periods where period_key = '2018-19')", '"2019-06-15"',
  'Every period-specific source (including MLB.com) gives June 15; the June 25 figure appears only in a later generic explainer and is treated as an error. Both claims stay on record.'))

fs.writeFileSync(out, lines.join('\n'))
console.log(`wrote ${path.relative(repoRoot, out)}: ${allSources.length} sources, ${draft.drafts.length} drafts, ${intl.periods.length} periods, ${uniq.length} observations`)
